export function t(path) {
  return path.split(".").reduce((value, key) => value?.[key], vi) ?? path;
}

export function labelGroup(group) {
  return vi.muscleGroups[group] || group;
}

export function shortGroup(group) {
  return vi.muscleShort[group] || labelGroup(group);
}

export function groupSlug(group) {
  return vi.muscleSlug[group] || String(group).toLowerCase().replace(/\W+/g, "-");
}

export function labelEquipment(item) {
  return vi.equipment[item] || item;
}

export function labelLevel(level) {
  return vi.levels[level] || level;
}

export function labelGoal(goal) {
  return vi.goals[goal] || goal;
}

export function labelDifficulty(value) {
  return vi.difficulty[value] || `Độ khó ${value}`;
}

